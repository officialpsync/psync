// build-exercise-map.mjs
// Run from your project root: node build-exercise-map.mjs
//
// Reads the exercise list from the repo and writes
// src/lib/exerciseImageMap.ts — a Record<string, string> mapping
// lowercase exercise names to their exact repo folder id.
// The app uses this to look up the right image path.

import fs from "fs"

const EXERCISES_URL = "https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json"
const OUT = "./lib/exerciseImageMap.ts"

async function main() {
  console.log("Fetching exercise list…")
  const res = await fetch(EXERCISES_URL)
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const exercises = await res.json()
  console.log(`${exercises.length} exercises found`)

  // Build map: lowercase name -> exact id
  const entries = exercises.map((ex) => {
    const key = ex.name.toLowerCase().trim()
    return `  ${JSON.stringify(key)}: ${JSON.stringify(ex.id)},`
  })

  const content = `// Auto-generated by build-exercise-map.mjs — do not edit by hand
// Maps lowercase exercise name -> free-exercise-db folder id
const exerciseImageMap: Record<string, string> = {
${entries.join("\n")}
}

export default exerciseImageMap
`

  fs.writeFileSync(OUT, content, "utf8")
  console.log(`Written to ${OUT}  (${exercises.length} entries)`)
}

main().catch((err) => { console.error(err); process.exit(1) })
